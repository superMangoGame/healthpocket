const [atlasText, sourceText] = await Promise.all([
  readFile(atlasPath, "utf8"),
  readFile(sourcePath, "utf8"),
]);
const atlas = JSON.parse(atlasText);
const source = JSON.parse(sourceText);
const translated = new Map(
  Object.values(source).flat().map((part) => [part.id, part.nameCn]),
);

let missing = 0;
for (const part of atlas.parts) {
  const exact = exactNames[part.name.toLowerCase()];
  const fallback = translated.get(part.id);
  part.nameZh = exact || fallback;
  if (!part.nameZh) missing += 1;
}
if (missing) throw new Error(`仍有 ${missing} 个解剖结构缺少中文名`);

await writeFile(atlasPath, JSON.stringify(atlas));
console.log(`已写入 ${atlas.parts.length} 个独立中文解剖名称：${atlasPath}`);
